#!/usr/bin/env bash
# monitors.sh: monitor wizard + profiles (Hyprland + Waybar). Subcommands: list | setup | apply | mirror | solo

set -uo pipefail

CFG="${XDG_CONFIG_HOME:-$HOME/.config}"
HYPR_DIR="$CFG/hypr"
WAYBAR_DIR="$CFG/waybar"
PROFILES="$HYPR_DIR/monitor-profiles.json"
UNMIRRORED="$HYPR_DIR/monitor-profiles.unmirrored.json"
SOLO_STATE="$HYPR_DIR/monitor-solo.json"
ACTIVE_LUA="$HYPR_DIR/monitors_active.lua"
WAYBAR_CFG="$WAYBAR_DIR/config"
BARS_TEMPLATE="$WAYBAR_DIR/bars.json"
GAME_MODE_STATE="${XDG_STATE_HOME:-$HOME/.local/state}/hyprflow/game-mode"

msg()  { printf '\033[1;34m󰍹 monitors:\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m󰍹 monitors:\033[0m %s\n' "$*" >&2; }
notify() { command -v notify-send >/dev/null 2>&1 && notify-send -a "Monitors" "Monitors" "$*" || true; }

need() {
    command -v "$1" >/dev/null 2>&1 || { warn "missing '$1' (required)"; exit 1; }
}

detect_json() { hyprctl monitors all -j; }

clean_mode() { sed -E 's/Hz$//; s/@([0-9]+)\.[0-9]+$/@\1/'; }

cmd_list() {
    need jq
    {
        # CURRENT is what the monitor runs now ("off" when disabled, since
        # hyprctl keeps reporting its last mode); PREFERRED is what it
        # advertises as native, often 60 Hz even on high refresh panels.
        printf 'IDX|DESCRIPTION (identifier)|PORT|CURRENT|PREFERRED\n'
        detect_json | jq -r '
            to_entries[] | .value as $m |
            "\(.key)|\($m.description)|\($m.name)|\(if $m.disabled then "off" else "\($m.width)x\($m.height)@\($m.refreshRate * 100 | round / 100)Hz" end)|\($m.availableModes[0] // "?")"
        '
    } | column -t -s '|'
    printf '\nUse the DESCRIPTION column verbatim in Waybar / profiles.\n'
}

default_profile() {
    detect_json | jq '
        ([ .[] | (.width*.height) ] | max) as $maxarea
        | ([ .[] | (.width*.height) ] | index($maxarea)) as $pidx
        | [ to_entries[]
            | .key as $k | .value
            | {
                description: .description,
                mode: ((.availableModes[0] // "\(.width)x\(.height)@60Hz") | sub("Hz$";"")),
                scale: .scale,
                transform: 0,
                primary: ($k == $pidx),
                name: .name
              }
          ]
        | map(.bar = (if (.primary or (.name|startswith("eDP"))) then "full" else "minimal" end))
        | map(del(.name))
    '
}

sig_of_descriptions() { jq -r '[.[].description] | sort | join("|")'; }

# True unless the kernel reports the connector as disconnected (or cannot say).
port_connected() {
    local st
    st="$(cat /sys/class/drm/card*-"$1"/status 2>/dev/null | head -n1)"
    [ "${st:-connected}" = "connected" ]
}

port_for_desc() {
    jq -r --arg d "$1" '.[] | select(.description == $d) | .name' | head -n1
}

# Turn a profile (stdin) into a mirror profile: every monitor clones $1 (a
# description). All monitors get the largest resolution they have in common,
# each at the refresh rate closest to the one it had.
mirrorize() {
    local src="$1" detected
    detected="$(detect_json)"
    jq --arg src "$src" --argjson det "$detected" '
        def res: split("@")[0];
        def hz: (split("@")[1] // "60" | tonumber);
        def absv: if . < 0 then -. else . end;
        def modes($d): [ $det[] | select(.description == $d) | .availableModes[] | sub("Hz$"; "") ];
        . as $p
        | ([ $p[] | [ modes(.description)[] | res ] | unique ]
           | if length == 0 then [] else reduce .[1:][] as $r (.[0]; . - (. - $r)) end
           | sort_by(split("x") | map(tonumber) | .[0] * .[1]) | last) as $common
        | map(
            .mode as $cur
            | (if $common then
                  ([ modes(.description)[] | select(res == $common) ]
                   | sort_by((hz - ($cur | hz)) | absv) | first)
               else null end) as $m
            | (if $m then .mode = ($m | sub("\\.0+$"; "")) else . end)
            | if .description == $src then .primary = true | del(.mirror)
              else .primary = false | .transform = 0 | .mirror = $src end
          )'
}

save_profile() {
    local sig="$1" entries="$2" file="${3:-$PROFILES}"
    mkdir -p "$HYPR_DIR"
    [ -f "$file" ] || echo '{}' > "$file"
    local merged; merged="$(jq --arg s "$sig" --argjson e "$entries" '.[$s] = $e' "$file")"
    printf '%s\n' "$merged" > "$file"
}

generate() {
    local out_lua="$1" out_waybar="$2"
    local profile detected
    profile="$(cat)"
    detected="$(detect_json)"

    {
        printf -- '-- monitors_active.lua — GENERATED by monitors.sh. Do not edit by hand.\n'
        printf -- '-- Run `monitors.sh setup` to change the layout.\n\n'

        local x=0 pair=3
        local n; n="$(jq 'length' <<<"$profile")"
        local ws_lines=""
        local i
        for ((i=0; i<n; i++)); do
            local desc mode scale transform primary bar port w h logical portrait
            desc="$(jq -r ".[$i].description" <<<"$profile")"
            mode="$(jq -r ".[$i].mode" <<<"$profile")"
            scale="$(jq -r ".[$i].scale" <<<"$profile")"
            transform="$(jq -r ".[$i] | (.transform // (if .orientation == \"v\" then 3 else 0 end))" <<<"$profile")"
            primary="$(jq -r ".[$i].primary" <<<"$profile")"
            port="$(printf '%s' "$detected" | port_for_desc "$desc")"
            [ -z "$port" ] && continue

            # A monitor Hyprland still lists can be gone at the connector: a
            # switched off DisplayPort screen reports itself disconnected once
            # it sleeps. Enabling it then fails the whole commit and every
            # screen falls back to its default mode, so leave it out; the
            # hotplug apply adds it when it wakes up.
            if [ "$(jq -r ".[$i].disabled // false" <<<"$profile")" != "true" ] && ! port_connected "$port"; then
                continue
            fi

            # "disabled": switch it off explicitly. Leaving it out of the file
            # is not enough, Hyprland turns on any monitor it has no rule for.
            if [ "$(jq -r ".[$i].disabled // false" <<<"$profile")" = "true" ]; then
                printf -- 'hl.monitor({ output = "%s", disabled = true })\n' "$port"
                continue
            fi

            # optional "mirror": description of the source monitor -> clone it
            local mirror_desc mirror_port
            mirror_desc="$(jq -r ".[$i].mirror // empty" <<<"$profile")"
            if [ -n "$mirror_desc" ]; then
                mirror_port="$(printf '%s' "$detected" | port_for_desc "$mirror_desc")"
                if [ -n "$mirror_port" ]; then
                    printf -- 'hl.monitor({ output = "%s", mode = "%s", position = "auto", scale = %s, mirror = "%s" })\n' \
                        "$port" "$mode" "$scale" "$mirror_port"
                    continue
                fi
            fi

            w="${mode%x*}"
            h="${mode#*x}"; h="${h%@*}"
            # transforms 1/3/5/7 rotate 90°/270° -> swap width/height (portrait)
            if [ $((transform % 2)) -eq 1 ]; then portrait=1; else portrait=0; fi
            if [ "$portrait" = "1" ]; then
                logical="$(awk -v a="$h" -v s="$scale" 'BEGIN{printf "%d", a/s}')"
            else
                logical="$(awk -v a="$w" -v s="$scale" 'BEGIN{printf "%d", a/s}')"
            fi

            printf -- 'hl.monitor({ output = "%s", mode = "%s", position = "%dx0", scale = %s, transform = %d })\n' \
                "$port" "$mode" "$x" "$scale" "$transform"

            local layoutopt=""
            [ "$portrait" = "1" ] && layoutopt=', layout_opts = { orientation = "top" }'
            if [ "$primary" = "true" ]; then
                ws_lines+=$(printf 'hl.workspace_rule({ workspace = "1", monitor = "%s"%s })' "$port" "$layoutopt")$'\n'
                ws_lines+=$(printf 'hl.workspace_rule({ workspace = "2", monitor = "%s"%s })' "$port" "$layoutopt")$'\n'
            else
                ws_lines+=$(printf 'hl.workspace_rule({ workspace = "%d", monitor = "%s"%s })' "$pair" "$port" "$layoutopt")$'\n'
                ws_lines+=$(printf 'hl.workspace_rule({ workspace = "%d", monitor = "%s"%s })' "$((pair+1))" "$port" "$layoutopt")$'\n'
                pair=$((pair+2))
            fi

            x=$((x + logical))
        done

        printf -- '\n'
        printf -- '%s\n' "$ws_lines"
    } > "$out_lua"

    if [ ! -f "$BARS_TEMPLATE" ]; then
        warn "$BARS_TEMPLATE not found; skipping waybar regeneration"
        return 0
    fi

    local bars='[]'
    local n; n="$(jq 'length' <<<"$profile")"
    local i
    for ((i=0; i<n; i++)); do
        local desc bar port logical mode transform scale w h archetype fw portrait
        desc="$(jq -r ".[$i].description" <<<"$profile")"
        bar="$(jq -r ".[$i].bar" <<<"$profile")"
        [ "$bar" = "none" ] && continue
        [ -n "$(jq -r ".[$i].mirror // empty" <<<"$profile")" ] && continue
        [ "$(jq -r ".[$i].disabled // false" <<<"$profile")" = "true" ] && continue
        port="$(printf '%s' "$detected" | port_for_desc "$desc")"
        [ -z "$port" ] && continue
        archetype="$(jq -c --arg t "$bar" '.[$t] // empty' "$BARS_TEMPLATE")"
        [ -z "$archetype" ] && { warn "bar type '$bar' not in bars.json; skipping"; continue; }
        mode="$(jq -r ".[$i].mode" <<<"$profile")"
        transform="$(jq -r ".[$i] | (.transform // (if .orientation == \"v\" then 3 else 0 end))" <<<"$profile")"
        scale="$(jq -r ".[$i].scale" <<<"$profile")"
        w="${mode%x*}"; h="${mode#*x}"; h="${h%@*}"
        if [ $((transform % 2)) -eq 1 ]; then portrait=1; else portrait=0; fi
        if [ "$portrait" = "1" ]; then
            logical="$(awk -v a="$h" -v s="$scale" 'BEGIN{printf "%d", a/s}')"
        else
            logical="$(awk -v a="$w" -v s="$scale" 'BEGIN{printf "%d", a/s}')"
        fi
        fw=$((logical - 120)); [ "$fw" -lt 400 ] && fw=$logical

        local barjson
        barjson="$(jq -c --arg out "$port" --argjson w "$fw" \
            'del(._comment) | .output = [$out] | (if has("width") then . else .width = $w end)' \
            <<<"$archetype")"
        bars="$(jq --argjson b "$barjson" '. + [$b]' <<<"$bars")"
    done
    printf '%s\n' "$bars" | jq '.' > "$out_waybar"
}

# Moves every workspace that sits on the wrong monitor back to the one its
# rule names. Hyprland moves a monitor's workspaces elsewhere when it goes off
# (solo, mirror, unplug) and leaves them there when it comes back. Focus ends
# where it was. Only monitors that are on are used as targets.
restore_workspaces() {
    local rules workspaces enabled focused ws mon cur moved=0
    rules="$(grep -oE 'workspace = "[0-9]+", monitor = "[^"]+"' "$ACTIVE_LUA" \
        | sed -E 's/workspace = "([0-9]+)", monitor = "([^"]+)"/\1 \2/')"
    [ -z "$rules" ] && return 0
    workspaces="$(hyprctl workspaces -j)"
    enabled="$(hyprctl monitors -j | jq -r '.[].name')"
    focused="$(hyprctl activeworkspace -j | jq -r '.id')"
    while read -r ws mon; do
        grep -qx "$mon" <<<"$enabled" || continue
        cur="$(jq -r --argjson w "$ws" '.[] | select(.id == $w) | .monitor' <<<"$workspaces")"
        { [ -z "$cur" ] || [ "$cur" = "$mon" ]; } && continue
        hyprctl dispatch "hl.dsp.focus({ workspace = $ws })" >/dev/null
        hyprctl dispatch "hl.dsp.workspace.move({ monitor = \"$mon\" })" >/dev/null
        moved=1
    done <<<"$rules"
    [ "$moved" -eq 1 ] && hyprctl dispatch "hl.dsp.focus({ workspace = $focused })" >/dev/null
    return 0
}

# The solo layout for the monitors detected now: the solo screen as recorded,
# every other one switched off, whatever set is connected at the moment.
solo_profile() {
    jq -c --slurpfile st "$SOLO_STATE" '
        ($st[0].entry) as $e
        | [$e] + [ .[] | select(.description != $e.description) | {description, disabled: true, bar: "none"} ]
    ' <<<"$1"
}

# cmd_apply [PROFILE]: without an argument, the profile comes from solo mode
# while it is on, else from the saved one for the connected set.
cmd_apply() {
    need jq
    local detected sig profile="${1:-}" used_default=0
    detected="$(detect_json)"
    sig="$(printf '%s' "$detected" | sig_of_descriptions)"

    # Solo mode is a state, not a profile. A switched off DisplayPort monitor
    # reports itself disconnected once it goes to sleep, which changes the
    # connected set; keying solo on the set would then fall back to another
    # layout and wake everything up. While the solo screen is connected, it
    # stays the only one on.
    if [ -z "$profile" ] && [ -f "$SOLO_STATE" ] && jq -e --slurpfile st "$SOLO_STATE" \
            'any(.[]; .description == $st[0].entry.description)' <<<"$detected" >/dev/null 2>&1; then
        profile="$(solo_profile "$detected")"
        msg "solo on: $(jq -r '.entry.description' "$SOLO_STATE")"
    fi

    if [ -n "$profile" ]; then
        :
    elif [ -f "$PROFILES" ] && jq -e --arg s "$sig" 'has($s)' "$PROFILES" >/dev/null 2>&1; then
        profile="$(jq -c --arg s "$sig" '.[$s]' "$PROFILES")"
        msg "profile found for this monitor set"
    else
        profile="$(default_profile)"
        used_default=1
        msg "no profile for this set → using default (horizontal, primary=largest)"
    fi

    local tmp_lua tmp_wb
    tmp_lua="$(mktemp)"; tmp_wb="$(mktemp)"
    printf '%s' "$profile" | generate "$tmp_lua" "$tmp_wb"

    mkdir -p "$HYPR_DIR" "$WAYBAR_DIR"

    # Reload only if the lua changed: a hotplug hl.on handler calls apply, so
    # guarding the reload prevents an event -> reload -> event loop.
    local lua_changed=0 wb_changed=0
    if ! cmp -s "$tmp_lua" "$ACTIVE_LUA" 2>/dev/null; then lua_changed=1; fi
    if ! cmp -s "$tmp_wb" "$WAYBAR_CFG" 2>/dev/null; then wb_changed=1; fi

    if [ "$lua_changed" -eq 1 ]; then
        mv "$tmp_lua" "$ACTIVE_LUA"
        msg "layout changed; reloading Hyprland…"
        hyprctl reload >/dev/null 2>&1 || true
        # A monitor switched back on (solo off, mirror off, a replug) comes up
        # without its wallpaper: awww does not repaint it by itself. Detached
        # and a moment later, once the daemon has seen the new output.
        if command -v awww >/dev/null 2>&1; then
            setsid sh -c 'sleep 1; awww restore' >/dev/null 2>&1 < /dev/null 9>&- &
        fi
        # Same wait for the workspaces: the monitors must be on to take them.
        ( sleep 1; restore_workspaces ) >/dev/null 2>&1 < /dev/null 9>&- &
    else
        rm -f "$tmp_lua"
    fi

    if [ "$wb_changed" -eq 1 ]; then
        mv "$tmp_wb" "$WAYBAR_CFG"
    else
        rm -f "$tmp_wb"
    fi

    # game-mode.sh hides Waybar and brings it back itself when it ends.
    if [ -f "$GAME_MODE_STATE" ]; then
        msg "game mode on: leaving Waybar hidden"
    elif [ "$wb_changed" -eq 1 ] || ! pgrep -x waybar >/dev/null 2>&1; then
        killall -w waybar >/dev/null 2>&1 || true
        # 9>&- : don't let Waybar (and its children) inherit the apply lock
        setsid waybar >/dev/null 2>&1 < /dev/null 9>&- &
        msg "Waybar (re)started"
    fi

    [ "$lua_changed" -eq 0 ] && [ "$wb_changed" -eq 0 ] && msg "no changes" || true
    [ "$used_default" -eq 1 ] && notify "Using default layout. Run 'monitors.sh setup' to customize." || true
}

ask() {
    local p="$1" d="${2:-}" a
    read -r -p "$p" a < /dev/tty || a=""
    printf '%s' "${a:-$d}"
}

cmd_setup() {
    need jq
    exec < /dev/tty
    local detected n
    detected="$(detect_json)"
    n="$(jq 'length' <<<"$detected")"
    [ "$n" -eq 0 ] && { warn "no monitors detected"; exit 1; }

    msg "Detected $n monitor(s):"
    cmd_list
    printf '\n'

    local entries='[]' disabled='[]'
    local i
    for ((i=0; i<n; i++)); do
        local desc port mode scale en trans bar
        desc="$(jq -r ".[$i].description" <<<"$detected")"
        port="$(jq -r ".[$i].name" <<<"$detected")"
        mode="$(jq -r ".[$i] | (.availableModes[0] // \"\(.width)x\(.height)@60Hz\")" <<<"$detected" | clean_mode)"
        scale="$(jq -r ".[$i].scale" <<<"$detected")"

        printf '\n\033[1m── %s (%s) ──\033[0m\n' "$desc" "$port"
        en="$(ask "  Enable this monitor? [Y/n]: " "y")"
        case "$en" in [nN]*)
            printf '  → disabled\n'
            disabled="$(jq --arg desc "$desc" '. + [{description:$desc, disabled:true, bar:"none"}]' <<<"$disabled")"
            continue ;;
        esac

        # Resolution: the preferred one by default. A TV often prefers 4K at
        # 30 Hz, where 1080p at 60 Hz plays far better, so offer the rest too,
        # largest first, each with every rate it offers (fastest first).
        local res resolutions rates k choice def
        res="${mode%@*}"
        mapfile -t resolutions < <(jq -r ".[$i].availableModes[] | sub(\"Hz\$\"; \"\")" <<<"$detected" \
            | awk -F@ '{ sub(/\.0+$/, "", $2); if (!(($1, $2) in seen)) { seen[$1, $2]; rates[$1] = rates[$1] " " $2 } }
                       END { for (r in rates) { split(r, d, "x"); printf "%d %s%s\n", d[1] * d[2], r, rates[r] } }' \
            | sort -k1,1nr | while read -r _ r list; do
                  printf '%s %s\n' "$r" "$(tr ' ' '\n' <<<"$list" | sort -rnu | paste -sd/ | sed 's|/| / |g')"
              done)
        if [ ${#resolutions[@]} -gt 1 ]; then
            def=1
            printf '    Resolution (refresh rates):\n'
            for k in "${!resolutions[@]}"; do
                [ "${resolutions[k]%% *}" = "$res" ] && def=$((k + 1))
                printf '      %2d) %-10s %s Hz\n' "$((k + 1))" "${resolutions[k]%% *}" "${resolutions[k]#* }"
            done
            choice="$(ask "  Resolution [1-${#resolutions[@]}] (default $def, preferred): " "$def")"
            case "$choice" in ''|*[!0-9]*) choice=$def ;; esac
            { [ "$choice" -ge 1 ] && [ "$choice" -le ${#resolutions[@]} ]; } || choice=$def
            res="${resolutions[choice - 1]%% *}"
        fi

        # Refresh rates offered at that resolution, fastest first. The
        # preferred mode is often 60 Hz even on high refresh panels, so default
        # to the fastest instead, and only accept a rate from this list.
        mapfile -t rates < <(jq -r --arg r "$res@" ".[$i].availableModes[]
            | select(startswith(\$r)) | sub(\"Hz\$\"; \"\") | split(\"@\")[1]
            | sub(\"\\\\.0+\$\"; \"\")" <<<"$detected" | sort -rnu)
        if [ ${#rates[@]} -gt 1 ]; then
            printf '    Refresh rate at %s:' "$res"
            for k in "${!rates[@]}"; do printf '  %d) %s Hz' "$((k + 1))" "${rates[k]}"; done
            printf '\n'
            choice="$(ask "  Refresh [1-${#rates[@]}] (default 1): " "1")"
            case "$choice" in ''|*[!0-9]*) choice=1 ;; esac
            { [ "$choice" -ge 1 ] && [ "$choice" -le ${#rates[@]} ]; } || choice=1
        else
            choice=1
        fi
        [ ${#rates[@]} -gt 0 ] && mode="$res@${rates[choice - 1]}"

        printf '    Rotation: 0=normal  1=90°(portrait)  2=180°(flipped)  3=270°(portrait)\n'
        printf '              4-7 = mirrored (4=normal, 5=90°, 6=180°, 7=270°)\n'
        trans="$(ask "  Transform [0-7] (default 0): " "0")"
        case "$trans" in ''|*[!0-7]*) trans=0 ;; esac

        scale="$(ask "  Scale (default $scale): " "$scale")"
        bar="$(ask "  Waybar bar: [f]ull / [m]inimal / [n]one (default f): " "f")"
        case "$bar" in [mM]*) bar="minimal" ;; [nN]*) bar="none" ;; *) bar="full" ;; esac

        entries="$(jq \
            --arg desc "$desc" --arg mode "$mode" --argjson scale "$scale" \
            --argjson trans "$trans" --arg bar "$bar" \
            '. + [{description:$desc, mode:$mode, scale:$scale, transform:$trans, primary:false, bar:$bar}]' \
            <<<"$entries")"
    done

    local cnt; cnt="$(jq 'length' <<<"$entries")"
    [ "$cnt" -eq 0 ] && { warn "no monitors enabled"; exit 1; }

    printf '\n\033[1mOrder left → right\033[0m (enabled monitors):\n'
    local j
    for ((j=0; j<cnt; j++)); do printf '  %d) %s\n' "$j" "$(jq -r ".[$j].description" <<<"$entries")"; done
    local ord; ord="$(ask "  Indices separated by space (default 0..$((cnt-1))): " "")"
    if [ -n "$ord" ]; then
        entries="$(jq -c -n --argjson e "$entries" --arg ord "$ord" '
            ($ord | split(" ") | map(tonumber)) as $idx | [ $idx[] | $e[.] ]')"
    fi

    printf '\n\033[1mPrimary monitor\033[0m (gets workspaces 1 and 2):\n'
    for ((j=0; j<cnt; j++)); do printf '  %d) %s\n' "$j" "$(jq -r ".[$j].description" <<<"$entries")"; done
    local prim; prim="$(ask "  Primary index (default 0): " "0")"
    entries="$(jq --argjson p "$prim" 'to_entries | map(.value.primary = (.key == $p)) | map(.value)' <<<"$entries")"

    local sig; sig="$(printf '%s' "$detected" | sig_of_descriptions)"
    if [ "$cnt" -gt 1 ]; then
        printf '\n\033[1mMirror\033[0m (every monitor clones the primary, same resolution):\n'
        local mir; mir="$(ask "  Mirror mode? [y/N]: " "n")"
        case "$mir" in [yY]*)
            save_profile "$sig" "$entries" "$UNMIRRORED"
            entries="$(mirrorize "$(jq -r '.[] | select(.primary) | .description' <<<"$entries")" <<<"$entries")"
            ;;
        esac
    fi

    entries="$(jq -c -n --argjson e "$entries" --argjson d "$disabled" '$e + $d')"
    save_profile "$sig" "$entries"
    msg "profile saved for: $sig"

    cmd_apply
}

cmd_mirror() {
    need jq
    local action="${1:-toggle}" src="${2:-}"
    local detected sig profile
    detected="$(detect_json)"
    sig="$(printf '%s' "$detected" | sig_of_descriptions)"
    [ "$(jq 'length' <<<"$detected")" -lt 2 ] && { warn "mirror needs at least 2 monitors"; exit 1; }

    if [ -f "$PROFILES" ] && jq -e --arg s "$sig" 'has($s)' "$PROFILES" >/dev/null 2>&1; then
        profile="$(jq -c --arg s "$sig" '.[$s]' "$PROFILES")"
    else
        profile="$(default_profile)"
    fi

    local mirrored=0
    jq -e 'any(.[]; .mirror)' <<<"$profile" >/dev/null && mirrored=1
    if [ "$action" = "toggle" ]; then
        [ "$mirrored" -eq 1 ] && action=off || action=on
    fi

    case "$action" in
        on)
            # source: argument (description or port), else the primary monitor
            if [ -n "$src" ]; then
                local d; d="$(jq -r --arg s "$src" '.[] | select(.name == $s or .description == $s) | .description' <<<"$detected" | head -n1)"
                [ -z "$d" ] && { warn "unknown monitor: $src"; exit 1; }
                src="$d"
            else
                src="$(jq -r '(map(select(.primary))[0] // .[0]).description' <<<"$profile")"
            fi
            # remember the extended layout so `mirror off` can restore it
            [ "$mirrored" -eq 0 ] && save_profile "$sig" "$profile" "$UNMIRRORED"
            profile="$(mirrorize "$src" <<<"$profile")"
            msg "mirroring onto: $src"
            ;;
        off)
            if [ -f "$UNMIRRORED" ] && jq -e --arg s "$sig" 'has($s)' "$UNMIRRORED" >/dev/null 2>&1; then
                profile="$(jq -c --arg s "$sig" '.[$s]' "$UNMIRRORED")"
            else
                profile="$(default_profile)"
            fi
            msg "mirror off: back to extended layout"
            ;;
        *) warn "usage: monitors.sh mirror [on [MONITOR]|off|toggle]"; exit 1 ;;
    esac

    save_profile "$sig" "$profile"
    cmd_apply
}

# solo on [MONITOR [MODE]]: only that monitor stays on (the TV, say; the
# primary one when none is given), optionally in another mode; the rest are
# switched off. The saved profiles are left alone: solo lives in its own state
# file, which apply honours for as long as it exists. solo off removes it.
cmd_solo() {
    need jq
    local action="${1:-toggle}" target="${2:-}" mode="${3:-}"
    local detected sig profile
    detected="$(detect_json)"
    sig="$(printf '%s' "$detected" | sig_of_descriptions)"

    if [ "$action" = "toggle" ]; then
        [ -f "$SOLO_STATE" ] && action=off || action=on
    fi

    case "$action" in
        on)
            if [ -f "$PROFILES" ] && jq -e --arg s "$sig" 'has($s)' "$PROFILES" >/dev/null 2>&1; then
                profile="$(jq -c --arg s "$sig" '.[$s]' "$PROFILES")"
            else
                profile="$(default_profile)"
            fi
            # No monitor given: keep the primary one, as mirror does.
            [ -z "$target" ] && target="$(jq -r '(map(select(.primary))[0] // .[0]).description' <<<"$profile")"
            local d; d="$(jq -r --arg s "$target" '.[] | select(.name == $s or .description == $s) | .description' <<<"$detected" | head -n1)"
            [ -z "$d" ] && { warn "unknown monitor: $target"; exit 1; }
            if [ -n "$mode" ] && ! jq -e --arg d "$d" --arg m "$mode" '
                    .[] | select(.description == $d) | .availableModes
                    | map(sub("Hz$"; "")) | any(. == $m or startswith($m + "."))' <<<"$detected" >/dev/null; then
                warn "$d does not offer $mode"; exit 1
            fi
            # Its settings from the profile; a monitor missing from it (a TV
            # plugged in after setup) comes from the default layout.
            local entry
            entry="$(jq -c --arg d "$d" --argjson def "$(default_profile)" '
                ([ .[] | select(.description == $d) ] + [ $def[] | select(.description == $d) ])[0]
                | del(.disabled, .mirror) | .primary = true
                | .bar = (if .bar == "none" or .bar == null then "full" else .bar end)' <<<"$profile")"
            [ -n "$mode" ] && entry="$(jq -c --arg m "$mode" '.mode = $m' <<<"$entry")"
            mkdir -p "$HYPR_DIR"
            jq -n --argjson e "$entry" --arg s "$sig" '{entry: $e, sig: $s}' > "$SOLO_STATE"
            cmd_apply
            ;;
        off)
            [ -f "$SOLO_STATE" ] || { msg "solo is already off"; return 0; }
            # Restore the layout of the set that was connected when solo began,
            # even if a monitor is still asleep and missing: generate skips it,
            # and the hotplug apply places it once it shows up again.
            local was; was="$(jq -r '.sig' "$SOLO_STATE")"
            rm -f "$SOLO_STATE"
            if [ -f "$PROFILES" ] && jq -e --arg s "$was" 'has($s)' "$PROFILES" >/dev/null 2>&1; then
                profile="$(jq -c --arg s "$was" '.[$s]' "$PROFILES")"
            else
                profile=""
            fi
            msg "solo off: back to the previous layout"
            cmd_apply "$profile"
            ;;
        *) warn "usage: monitors.sh solo [on [MONITOR [MODE]]|off|toggle]"; exit 1 ;;
    esac
}

# Waits for a running apply instead of skipping. At login several run at once
# (the startup one plus a hotplug per monitor that wakes late); skipping lost
# the last one, which is the only one that saw every monitor, and left the
# default layout in place. Each waits, then reads the monitors connected by
# then; no loop, since apply only reloads when the output changed.
take_lock() {
    exec 9>/tmp/monitors-apply.lock
    flock -w 30 9 || { warn "another run is stuck, skipping"; exit 0; }
}

case "${1:-apply}" in
    list)  cmd_list ;;
    setup) cmd_setup ;;
    apply)  take_lock; cmd_apply ;;
    mirror) take_lock; cmd_mirror "${2:-toggle}" "${3:-}" ;;
    solo)   take_lock; cmd_solo "${2:-toggle}" "${3:-}" "${4:-}" ;;
    *) warn "usage: monitors.sh [list|setup|apply|mirror [on [MONITOR]|off|toggle]|solo [on [MONITOR [MODE]]|off|toggle]]"; exit 1 ;;
esac
