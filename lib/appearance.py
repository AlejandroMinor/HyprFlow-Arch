#!/usr/bin/env python3
"""The panels' tone (Super+K > Appearance): Quickshell, rofi and swaync.

The tones are dotconfig/quickshell/hyprflow/palettes.json; the one in use and
what was tweaked per tone (card: the background's opacity, blur: the glass,
text: its colour) are state/appearance.json. A tone `"from": "wallust"` takes its background
and text from the wallust palette and its accent from the LED colour (the
theme picked in the Theme tab, or the wallpaper's); wallust-theme-manager.sh
runs `apply` after each change. Colors.qml reads all of it itself; rofi and swaync get
their colours written out (colors.rasi, colors.css), and Hyprland the glass
(state/glass.lua, read by plugins.lua).

    appearance.py tone NAME      use a tone
    appearance.py next           the next tone
    appearance.py set card|blur VALUE
    appearance.py set text #RRGGBB|default
    appearance.py glass on|off   the panels' glass, for every tone
    appearance.py reset          the tone's own card, blur and text again
    appearance.py apply          write everything out again
    appearance.py get            the tone in use
"""

import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hyprflow import paths  # noqa: E402

PALETTES = paths.CONFIG / "quickshell" / "hyprflow" / "palettes.json"
STATE = paths.HYPRFLOW_STATE / "appearance.json"
GLASS = paths.HYPRFLOW_STATE / "glass.lua"
ROFI = paths.CONFIG / "rofi" / "hyprflow" / "colors.rasi"
SWAYNC = paths.CONFIG / "swaync" / "colors.css"

WALLUST = Path(os.environ.get("WALLUST_SH_PALETTE")
               or paths.CACHE / "wallust" / "colors" / "colors-rofi-sh.conf")
LED = paths.CACHE / "wallust" / "led-color"

TWEAKS = {"card": (0.05, 0.95), "blur": (0.0, 4.0)}  # what `set` takes, and its range


def palettes():
    return json.loads(PALETTES.read_text())


def load_state():
    try:
        state = json.loads(STATE.read_text())
    except (OSError, ValueError):
        state = {}
    return state if isinstance(state, dict) else {}


def save_state(state):
    STATE.parent.mkdir(parents=True, exist_ok=True)
    STATE.write_text(json.dumps(state, indent=2) + "\n")


def current(state, tones):
    tone = state.get("tone")
    return tone if tone in tones else next(iter(tones))


def wallust():
    """The wallust palette (background, foreground, colorN) and the LED colour
    as "led"; what cannot be read is left out."""
    colours = {}
    try:
        for key, value in re.findall(r"^(\w+)='(#[0-9A-Fa-f]{6})'", WALLUST.read_text(), re.M):
            colours[key] = value.upper()
    except OSError:
        pass
    try:
        led = LED.read_text().strip()
        if re.fullmatch(r"[0-9A-Fa-f]{6}", led):
            colours["led"] = "#" + led.upper()
    except OSError:
        pass
    return colours


def resolve(tones, state):
    """The tone in use, with its tweaks on top."""
    name = current(state, tones)
    tone = json.loads(json.dumps(tones[name]))
    if tone.get("from") == "wallust":
        w = wallust()
        tone["background"] = w.get("background", tone["background"])
        tone["foreground"] = w.get("foreground", tone["foreground"])
        tone["accent"] = w.get("led", w.get("color5", tone["accent"]))
    tweaks = state.get(name, {})
    if "card" in tweaks:
        tone["card"] = tweaks["card"]
    if "blur" in tweaks:
        tone["glass"]["blur"] = tweaks["blur"]
    if "text" in tweaks:
        tone["foreground"] = tweaks["text"]
    return name, tone


def rgb(hex_colour):
    h = hex_colour.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rgba_hex(hex_colour, alpha):
    """#RRGGBBAA, as rofi writes it."""
    return "#{:02X}{:02X}{:02X}{:02X}".format(*rgb(hex_colour), round(alpha * 255))


def css(hex_colour, alpha):
    return "rgba({}, {}, {}, {:g})".format(*rgb(hex_colour), round(alpha, 3))


def lifted(tone, alpha):
    """Colors.fg: secondary text drawn stronger where the tone asks for it."""
    return min(1, alpha + tone["lift"]) if alpha >= 0.3 else alpha


def rofi_colours(name, tone):
    fg, bg = tone["foreground"], tone["background"]
    return f"""/* Generated by lib/appearance.py from palettes.json ({name}): do not edit. */
* {{
    foreground: {fg};
    muted:      {rgba_hex(fg, lifted(tone, 0.45))};
    accent:     {fg};
    active:     {tone["accent"]};
    bg-solid:   {bg};

    bg-window:  {rgba_hex(bg, tone["card"])};
    bg-input:   #00000000;
    sel-bg:     {rgba_hex(*tone["selection"])};
    separator:  {rgba_hex(*tone["border"])};
}}
"""


def swaync_colours(name, tone):
    fg, bg = tone["foreground"], tone["background"]
    hover = css(*tone["selection"])
    return f"""/* Generated by lib/appearance.py from palettes.json ({name}): do not edit. */
:root {{
  --cc-bg: {css(bg, tone["card"])};
  --noti-border-color: {css(*tone["border"])};
  --noti-bg: {", ".join(map(str, rgb(bg)))};
  --noti-bg-alpha: {tone["card"]:g};
  --noti-bg-darker: {hover};
  --noti-bg-hover: {hover};
  --noti-bg-focus: transparent;
  --noti-close-bg: {css(fg, 0.08)};
  --noti-close-bg-hover: {css(fg, 0.15)};
  --text-color: {fg};
  --text-color-body: {css(fg, lifted(tone, 0.6))};
  --text-color-disabled: {css(fg, lifted(tone, 0.45))};
  --bg-selected: {tone["accent"]};
}}
"""


def glass_lua(name, tone, on=True):
    if not on:
        return f"-- Generated by lib/appearance.py ({name}): glass off, do not edit.\nreturn false\n"
    g = tone["glass"]
    tint = int(rgba_hex(*g["tint"])[1:], 16)
    return f"""-- Generated by lib/appearance.py from palettes.json ({name}): do not edit.
return {{
    blur_strength = {g["blur"]:g},
    brightness    = {g["brightness"]:g},
    contrast      = {g["contrast"]:g},
    saturation    = {g["saturation"]:g},
    tint_color    = 0x{tint:08X},
}}
"""


def write_if_changed(path, text):
    """True if PATH changed; a missing folder means that app is not set up."""
    if not path.parent.is_dir():
        return False
    try:
        if path.read_text() == text:
            return False
    except OSError:
        pass
    path.write_text(text)
    return True


def run(argv):
    if shutil.which(argv[0]):
        subprocess.run(argv, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False, timeout=10)


def apply(state):
    name, tone = resolve(palettes(), state)
    write_if_changed(ROFI, rofi_colours(name, tone))
    if write_if_changed(SWAYNC, swaync_colours(name, tone)):
        run(["swaync-client", "-rs"])
    GLASS.parent.mkdir(parents=True, exist_ok=True)
    if write_if_changed(GLASS, glass_lua(name, tone, state.get("glass", True))):
        run(["hyprctl", "reload"])


def main(args):
    tones = palettes()
    state = load_state()
    command = args[0] if args else "get"

    if command == "get":
        print(current(state, tones))
        return 0
    if command == "tone" and len(args) == 2 and args[1] in tones:
        state["tone"] = args[1]
    elif command == "next":
        names = list(tones)
        state["tone"] = names[(names.index(current(state, tones)) + 1) % len(names)]
    elif command == "set" and len(args) == 3 and args[1] == "text":
        tweaks = state.setdefault(current(state, tones), {})
        if args[2] == "default":
            tweaks.pop("text", None)
        elif re.fullmatch(r"#[0-9A-Fa-f]{6}", args[2]):
            tweaks["text"] = args[2].upper()
        else:
            return 2
    elif command == "set" and len(args) == 3 and args[1] in TWEAKS:
        try:
            value = float(args[2])
        except ValueError:
            return 2
        low, high = TWEAKS[args[1]]
        state.setdefault(current(state, tones), {})[args[1]] = round(min(high, max(low, value)), 3)
    elif command == "glass" and len(args) == 2 and args[1] in ("on", "off"):
        state["glass"] = args[1] == "on"
    elif command == "reset":
        state.pop(current(state, tones), None)
    elif command != "apply":
        print(__doc__.split("\n\n")[-1], file=sys.stderr)
        return 2

    save_state(state)
    apply(state)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
